"""Frontmatter parsing shared by bin/build and bin/check. stdlib only."""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKILLS = REPO / "skills"
GENERATED_MARK = "# generated by bin/build from SKILL.md frontmatter"
TRUE = {"true", "yes", "on", "1"}


def parse_frontmatter(text):
    """Minimal YAML subset: `key: value`, `key: >-`/`|` block scalars,
    quoted strings, and one nested mapping (`metadata:`)."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, "missing frontmatter"
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return None, "unterminated frontmatter"
    body = lines[1:end]
    data = {}
    i = 0
    while i < len(body):
        line = body[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if not m:
            return None, f"cannot parse frontmatter line {i + 2}: {line!r}"
        key, val = m.group(1), m.group(2).strip()
        i += 1
        if val in (">", ">-", "|", "|-"):
            chunk = []
            while i < len(body) and (body[i].startswith(" ") or not body[i].strip()):
                chunk.append(body[i].strip())
                i += 1
            joiner = " " if val.startswith(">") else "\n"
            data[key] = joiner.join(c for c in chunk if c).strip()
        elif val == "":
            nested = {}
            while i < len(body) and body[i].startswith(" "):
                nm = re.match(r"^\s+([A-Za-z0-9_-]+):\s*(.*)$", body[i])
                if nm:
                    nested[nm.group(1)] = unquote(nm.group(2).strip())
                i += 1
            data[key] = nested
        else:
            data[key] = unquote(val)
    return data, None


def unquote(s):
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    return s


def truthy(v):
    return isinstance(v, str) and v.strip().lower() in TRUE


def skill_dirs():
    return sorted(p for p in SKILLS.iterdir() if p.is_dir() and not p.name.startswith((".", "_")))


def display_name(name):
    return " ".join(w.capitalize() for w in name.split("-"))


def short_description(desc, limit=64):
    first = re.split(r"(?<=[.!?])\s", desc.strip(), maxsplit=1)[0].rstrip(".")
    if len(first) <= limit:
        return first
    cut = first[:limit].rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:-")


def yaml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_openai_yaml(fm):
    meta = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
    dn = meta.get("display-name") or display_name(fm["name"])
    sd = meta.get("short-description") or short_description(fm.get("description", ""))
    out = [GENERATED_MARK + " - do not edit by hand", "interface:",
           f"  display_name: {yaml_str(dn)}", f"  short_description: {yaml_str(sd)}"]
    if truthy(fm.get("disable-model-invocation")):
        out += ["policy:", "  allow_implicit_invocation: false"]
    return "\n".join(out) + "\n"
